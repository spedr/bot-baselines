"""Results tables for docs/results/roberta_mlp.md from runs/roberta_mlp/*/*/result.json.

    uv run python -m bb.methods.roberta_mlp.report            # print markdown
    uv run python -m bb.methods.roberta_mlp.report --write    # replace the RESULTS block of the doc

Reads only small result.json files (no dataset artifacts). Runs with a ExtScore column are listed as
plumbing checks only, never as results.
"""
from __future__ import annotations

import argparse
import re
from collections import defaultdict

import numpy as np

from ...harness import load_results
from ...paths import REPO_ROOT

DATASETS = ("cresci15", "twibot20", "twibot22")
NAMES = {"cresci15": "Cresci-2015", "twibot20": "TwiBot-20", "twibot22": "TwiBot-22"}
# spec section 6 (benchmark readme / Tables 2, 8): acc, "F1" as published, precision, recall, class of "F1"
PUBLISHED = {
    "twibot22": (72.07, 0.16, 20.53, 1.71, 63.28, 12.27, "bot"),
    "twibot20": (75.55, 0.18, 73.09, 0.59, 73.88, 72.38, "human"),
    "cresci15": (97.01, 0.13, 95.86, 0.19, 97.58, 94.11, "human (see below)"),
}
DOC = REPO_ROOT / "docs" / "results" / "roberta_mlp.md"
BEGIN, END = "<!-- RESULTS:BEGIN (generated by python -m bb.methods.roberta_mlp.report --write) -->", "<!-- RESULTS:END -->"


def ms(v, scale=100.0, nd=2) -> str:
    v = np.asarray([x for x in v if x is not None], float) * scale
    if not len(v):
        return "-"
    return f"{v.mean():.{nd}f} ± {v.std(ddof=1):.{nd}f}" if len(v) > 1 else f"{v[0]:.{nd}f}"


def groups(ds: str) -> dict:
    g = defaultdict(list)
    for r in load_results("roberta_mlp", ds):
        c = r["config"]
        g[(c.get("variant"), c.get("with_extscore") or (c.get("extscore_tag") if c.get("extscore") == "p" else None))].append(r)
    return g


def render() -> str:
    out = ["## Results (test split, primary selection = last epoch unless the variant says best_val, "
           "mean ± sd over seeds, %)", "",
           "| dataset | variant | seeds | acc | bot P | bot R | **bot F1** | human P | human R | human F1 | macro F1 | AUC |",
           "|---|---|---|---|---|---|---|---|---|---|---|---|"]
    sec = ["", "Secondary number (the other selection rule; best_val = bot-class val F1, deep copy):", "",
           "| dataset | variant | secondary | epochs | acc | bot F1 | human F1 | AUC |", "|---|---|---|---|---|---|---|---|"]
    res = ["", "## Resources (per seed; GPU shared with the embedding chain and other agents)", "",
           "| dataset | variant | seeds | wall s / seed | train s / epoch | peak RSS GB | cgroup peak GB | CUDA max alloc GB | train inputs on |",
           "|---|---|---|---|---|---|---|---|---|"]
    plumb = []
    for ds in DATASETS:
        for (variant, extscore), rs in sorted(groups(ds).items(), key=lambda kv: (kv[0][1] or "", kv[0][0] or "")):
            rs = sorted(rs, key=lambda r: (r["seed"], r["finished_at"]))
            seeds = sorted({r["seed"] for r in rs})
            if extscore:
                j = rs[-1]["extscore"]
                plumb.append(f"| {NAMES[ds]} | {variant} | {extscore} | {rs[-1]['n_params']} | "
                             f"{j['coverage'].get('test', {}).get('coverage', float('nan')):.3f} | "
                             f"{'passed' if not j['guard_problems'] else j['guard_problems']} | {rs[-1]['status']} |")
                continue
            # one run per seed (latest) for the tables
            by_seed = {r["seed"]: r for r in rs}
            rs = [by_seed[s] for s in seeds]
            t = [r["metrics"]["test"] for r in rs]
            col = lambda k, src=t: [m[k] for m in src]  # noqa: E731
            out.append(f"| {NAMES[ds]} | {variant} | {len(rs)} | {ms(col('accuracy'))} | {ms(col('precision'))} | "
                       f"{ms(col('recall'))} | **{ms(col('f1'))}** | {ms(col('precision_human'))} | "
                       f"{ms(col('recall_human'))} | {ms(col('f1_human'))} | {ms(col('macro_f1'))} | {ms(col('roc_auc'))} |")
            st = [r["secondary"]["metrics"]["test"] for r in rs]
            ss = [r["secondary"]["selection"] for r in rs]
            ep = [x.get("best_epoch", x.get("epoch")) for x in ss]
            sec.append(f"| {NAMES[ds]} | {variant} | {ss[0]['select']} | {', '.join(map(str, ep))} | {ms(col('accuracy', st))} | "
                       f"{ms(col('f1', st))} | {ms(col('f1_human', st))} | {ms(col('roc_auc', st))} |")
            mem = [r["memory"] for r in rs]
            res.append(f"| {NAMES[ds]} | {variant} | {len(rs)} | {np.mean([r['wall_seconds'] for r in rs]):.1f} | "
                       f"{np.mean([r['timing']['seconds_per_epoch'] for r in rs]):.3f} | "
                       f"{max(m['peak_rss_bytes'] for m in mem) / 1e9:.2f} | "
                       f"{max((m.get('cgroup') or {}).get('memory.peak', 0) for m in mem) / 1e9:.2f} | "
                       f"{max(m.get('cuda_max_allocated_bytes', 0) for m in mem) / 1e9:.3f} | "
                       f"{rs[0]['gpu']['placement']['train']} |")
    pub = ["", "Published (benchmark readme / Tables 2, 8; spec section 6):", "",
           "| dataset | acc | \"F1\" as published | P | R | class of that F1 |", "|---|---|---|---|---|---|"]
    for ds in DATASETS:
        a, sa, f, sf, p, r, c = PUBLISHED[ds]
        pub.append(f"| {NAMES[ds]} | {a:.2f} ± {sa:.2f} | {f:.2f} ± {sf:.2f} | {p:.2f} | {r:.2f} | {c} |")
    pl = ["", "ExtScore plumbing runs (synthetic column; NOT results):", "",
          "| dataset | variant | tag | params | test coverage | guard | status |", "|---|---|---|---|---|---|---|", *plumb]
    return "\n".join(out + pub + sec + res + pl) + "\n"


def main(argv=None) -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    a = ap.parse_args(argv)
    md = render()
    if not a.write:
        print(md)
        return
    doc = DOC.read_text()
    block = f"{BEGIN}\n{md}{END}"
    if BEGIN in doc:
        doc = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: block, doc, flags=re.S)
    else:
        doc = doc.replace("RESULTS\n", block + "\n", 1)
    DOC.write_text(doc)
    print(f"wrote {DOC}")


if __name__ == "__main__":
    main()
